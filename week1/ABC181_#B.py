
"""
[문제]
  1. 아무것도 쓰여있지 않은 칠판에, n번의 정수 연산들을 하고, 칠판에 쓸 것이다.
  2. i번째 연산에서, A_i부터 B_i까지를 쓰고, B_i - A_i + 1 개의 정수들을 모두 더할 것이다.
  3. N번의 연산이 끝나고 나서, 이 연산의 합들을 구하라.

[입력]
  1. 연산을 실행할 횟수 N (10만 이하)
  2. 수의 범위를 나타낼 A_i, B_i (100만 이하)
"""

n = int(input())

answer = 0

for _ in range(n) :
    a, b = map(int, input().split())
    answer += (b*(b+1))//2 - ((a-1)*a)//2

print(answer)